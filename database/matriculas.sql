-- PostgreSQL. Ejecutar después de crear alumnos y curso.
CREATE TABLE IF NOT EXISTS matriculas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alumno_id BIGINT NOT NULL REFERENCES alumnos(id),
    curso_id BIGINT NOT NULL REFERENCES curso(id),
    fecha DATE NOT NULL,
    estado VARCHAR(10) NOT NULL DEFAULT 'ACTIVA',
    CONSTRAINT uk_matricula_alumno_curso UNIQUE (alumno_id, curso_id),
    CONSTRAINT ck_matricula_estado CHECK (estado IN ('ACTIVA', 'CANCELADA'))
);
